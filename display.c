void load_fontpal_state(const ASN1_Value*v) {
  char name[9];
  ASN1_Value v0,v1;
  int i;
  if(v->class) goto bad;
  load_font(0,LOADFONT_RESET);
  load_palette(0,LOADPAL_RESET);
  if(v->type==ASN1_SEQUENCE) {
    if(asn1_first_of(&v0,v) || v0.class || v0.constructed) goto bad;
    if(v0.type==ASN1_OCTET_STRING && v0.length==0xE00) {
      if(!(font=malloc(0xE00))) err(1,"Allocation failed");
      memcpy(font,v0.data,0xE00);
    } else if(v0.type!=ASN1_NULL) {
      goto bad;
    }
    if(asn1_next_of(&v0,v) || v0.class || v0.type!=ASN1_SEQUENCE) goto bad;
    if(!asn1_first_of(&v1,&v0)) do {
      if(v1.class || v1.type!=ASN1_VISIBLE_STRING || v1.constructed || v1.length<1 || v1.length>8) goto bad;
      snprintf(name,9,"%*.*s",(int)v1.length,(int)v1.length,v1.data);
      load_palette(name,LOADPAL_BASE);
    } while(!asn1_next_of(&v1,&v0));
    if(asn1_next_of(&v0,v)) return;
    if(config.font_anim) {
      if(v0.class || (v0.type!=ASN1_NULL && v0.type!=ASN1_SEQUENCE)) goto bad;
      if(v0.type==ASN1_SEQUENCE) {
        nfontanim=asn1_count(&v0);
        fontanim=calloc(nfontanim,sizeof(FontAnim*));
        if(nfontanim && !fontanim) err(1,"Allocation failed");
        for(i=0;i<nfontanim;i++) {
          if(i?asn1_next_of(&v1,&v0):asn1_first_of(&v1,&v0)) goto bad;
          if(v1.type!=ASN1_OCTET_STRING || v1.length<8 || v1.length>0xE08) goto bad;
          if(v1.data[5]==FONTANIM_FULL && v1.data[6]*14!=v1.length-8) goto bad;
          fontanim[i]=malloc(sizeof(FontAnim)+v1.length-8);
          if(!fontanim[i]) err(1,"Allocation failed");
          fontanim[i][0]=(FontAnim){v1.data[0],v1.data[1],v1.data[2],v1.data[3],v1.data[4],v1.data[5],v1.data[6],v1.data[7]};
          if(v1.length>8) memcpy(fontanim[i]->raster,v1.data+8,v1.length-8);
        }
      }
    }
  } else if(v->type!=ASN1_NULL) {
    bad: errx(1,"Font/palette state in save game file has unexpected format");
  }
}

void save_fontpal_state(ASN1_Encoder*enc) {
  int i;
  FILE*f;
  if(!font && !palinf[0].name[0] && !palinf[1].name[0] && !palinf[2].name[0]) {
    asn1_primitive(enc,ASN1_UNIVERSAL,ASN1_NULL,0,0);
    return;
  }
  asn1_construct(enc,ASN1_UNIVERSAL,ASN1_SEQUENCE,0);
    if(font) asn1_primitive(enc,ASN1_UNIVERSAL,ASN1_OCTET_STRING,font,0xE00); else asn1_primitive(enc,ASN1_UNIVERSAL,ASN1_NULL,0,0);
    asn1_construct(enc,ASN1_UNIVERSAL,ASN1_SEQUENCE,0);
      if(palinf[0].name[0] && palinf[0].which) asn1_encode_c_string(enc,ASN1_VISIBLE_STRING,palinf[0].name);
      if(palinf[1].name[0] && palinf[1].which) asn1_encode_c_string(enc,ASN1_VISIBLE_STRING,palinf[1].name);
      if(palinf[2].name[0] && palinf[2].which) asn1_encode_c_string(enc,ASN1_VISIBLE_STRING,palinf[2].name);
    asn1_end(enc);
    if(nfontanim) {
      asn1_construct(enc,ASN1_UNIVERSAL,ASN1_SEQUENCE,0);
        for(i=0;i<nfontanim;i++) {
          f=asn1_primitive_stream(enc,ASN1_UNIVERSAL,ASN1_OCTET_STRING);
          if(!f) err(1,"Allocation failed");
          fputc(fontanim[i]->lo,f);
          fputc(fontanim[i]->hi,f);
          fputc(fontanim[i]->speed,f);
          fputc(fontanim[i]->delay,f);
          fputc(fontanim[i]->control,f);
          fputc(fontanim[i]->kind,f);
          fputc(fontanim[i]->arg1,f);
          fputc(fontanim[i]->arg2,f);
          if(fontanim[i]->kind==FONTANIM_FULL) fwrite(fontanim[i]->raster,14,fontanim[i]->arg1,f);
          asn1_end(enc);
        }
      asn1_end(enc);
    } else {
      asn1_encode_null(enc);
    }
  asn1_end(enc);
}

void init_display(void) {
  if(scrn) goto clear;
  if(SDL_Init(SDL_INIT_TIMER|SDL_INIT_VIDEO)) errx(1,"SDL error: %s",SDL_GetError());
  atexit(SDL_Quit);
  scrn=SDL_SetVideoMode(config.show_status?648:640,config.show_status?372:350,8,SDL_SWSURFACE|(config.full_screen?SDL_FULLSCREEN:0));
  if(!scrn) errx(1,"SDL error: %s",SDL_GetError());
  if(config.joy_name || config.joy_index>=0) {
    if(SDL_InitSubSystem(SDL_INIT_JOYSTICK)) errx(1,"SDL error: %s",SDL_GetError());
    if(config.joy_name && config.joy_index<0) {
      int n=SDL_NumJoysticks();
      int i;
      for(i=0;i<n;i++) if(!strcmp(SDL_JoystickName(i),config.joy_name)) {
        config.joy_index=i;
        break;
      }
      if(config.joy_index<0) errx(1,"Cannot find joystick named \"%s\"",config.joy_name);
    }
    joy=SDL_JoystickOpen(config.joy_index);
    if(!joy) errx(1,"SDL error: %s",SDL_GetError());
    SDL_JoystickEventState(SDL_ENABLE);
  }
  if(config.video_gamma) {
    const char*s=config.video_gamma;
    float r,g,b;
    int i,j;
    gamma_r=r=strtod(s,(char**)&s);
    if(*s==';') ++s,gamma_g=g=strtod(s,(char**)&s); else gamma_g=g=r;
    if(*s==';') ++s,gamma_b=b=strtod(s,(char**)&s); else gamma_b=b=r;
    for(i=0;i<16;i++) {
      j=255.0*pow(palet[i].r/255.0,r); palet[i].r=j>255?255:j;
      j=255.0*pow(palet[i].g/255.0,g); palet[i].g=j>255?255:j;
      j=255.0*pow(palet[i].b/255.0,b); palet[i].b=j>255?255:j;
    }
  }
  SDL_SetColors(scrn,palet,0,34);
  SDL_SetColors(scrn,palet,0x30,16);
  switch(config.text_input) {
    case 0: SDL_EnableUNICODE(1); break;
#ifdef SDL_VIDEO_DRIVER_X11
    case 1:
      {
        int i;
        XModifierKeymap*mods;
        SDL_SysWMinfo info;
        SDL_VERSION(&info.version);
        if(!SDL_GetWMInfo(&info) || info.subsystem!=SDL_SYSWM_X11) goto bad1;
        xdisplay=info.info.x11.display;
        xwindow=info.info.x11.window;
        if(xlock=info.info.x11.lock_func) xlock();
        if(mods=XGetModifierMapping(xdisplay)) {
          for(i=3*mods->max_keypermod;i<8*mods->max_keypermod;i++) {
#ifdef CONFIG_USE_DEPRECATED_X11_FUNCTION
            switch(XKeycodeToKeysym(xdisplay,mods->modifiermap[i],0)) {
              case XK_Num_Lock: num_mask=1<<(i/mods->max_keypermod); break;
              case XK_Mode_switch: mode_switch_mask=1<<(i/mods->max_keypermod); break;
            }
#else
          KeySym*x=0;
          int j;
          if(mods->modifiermap[i] && (x=XGetKeyboardMapping(xdisplay,mods->modifiermap[i],1,&j)) && j>0) switch(*x) {
            case XK_Num_Lock: num_mask=1<<(i/mods->max_keypermod); break;
            case XK_Mode_switch: mode_switch_mask=1<<(i/mods->max_keypermod); break;
          }
          if(x) XFree(x);
#endif
          }
          XFreeModifiermap(mods);
        }
        if(xunlock=info.info.x11.unlock_func) xunlock();
        //TODO: handle input methods for arbitrary character sets instead of only ASCII
      }
      break;
#endif
    case 2: SDL_EnableUNICODE(0); break;
    default: bad1: errx(1,"Unrecognized text input mode (%d)",config.text_input);
  }
  SDL_EnableKeyRepeat(config.key_repeat_delay,config.key_repeat_interval);
  if(config.event_input==1) SDL_CreateThread(custom_event_thread,0);
#ifndef CONFIG_DISABLE_FRONT
  if(extern_in && extern_out) {
    frontsem=SDL_CreateSemaphore(0);
    if(!frontsem) errx(1,"Cannot create semaphore");
    SDL_CreateThread(custom_event_thread_1,extern_in);
  }
#endif
  clear:
  memset(v_color,7,80*25);
  memset(v_char,32,80*25);
  memset(v_font,VF_SYSTEM,80*25);
  memset(v_status,0,82);
}

void configure_colors(const char*t) {
  Uint32 a,b;
  char*z;
  if(*t=='*') {
    t++;
    for(a=0;a<16;a++) {
      if(t[0]<63 || t[0]>126) goto error;
      if(t[1]<63 || t[1]>126) goto error;
      if(t[2]<63 || t[2]>126) goto error;
      if(t[3]<63 || t[3]>126) goto error;
      b=((t[0]-63)<<18)+((t[1]-63)<<12)+((t[2]-63)<<6)+((t[3]-63)<<0);
      palet[a]=(SDL_Color){(b>>16)&255,(b>>8)&255,b&255};
      t+=4;
    }
    if(*t) goto error;
  } else if((*t>='0' && *t<='9') || (*t>='A' && *t<='F') || (*t>='a' && *t<='f')) {
    a=strtoul(t,(char**)&t,16);
    if(*t++!='=') goto error;
    b=strtoul(t,&z,16);
    if(*z || z!=t+6) goto error;
    palet[a&0x3F]=(SDL_Color){(b>>16)&255,(b>>8)&255,b&255};
  } else if(*t=='%' && t[1]=='0') {
    putchar('*');
    for(a=0;a<16;a++) {
      b=(palet[a].r<<16)|(palet[a].g<<8)|(palet[a].b<<0);
      putchar(((b>>18)&63)+63);
      putchar(((b>>12)&63)+63);
      putchar(((b>>6)&63)+63);
      putchar(((b>>0)&63)+63);
    }
    putchar('\n');
  } else if(*t) {
    error: errx(1,"Improper configuration in [Colors] division",t);
  }
}

void redisplay(void) {
  Uint8*p;
  Uint32 m;
  int a,b,c,d,r,x,y,z;
  if(!scrn) return;
  SDL_FillRect(scrn,0,32);
  SDL_LockSurface(scrn);
  r=scrn->pitch;
  p=scrn->pixels+(config.show_status?4*r+4:0);
  switch(v_mode) {
    case 0:
      for(z=y=0;y<25;y++,z+=80) {
        for(a=0;a<14;a++) {
          for(x=0;x<40;x++) {
            if(v_font[z+x]&VF_SYSTEM) {
              c=pcfont[14*v_char[z+x]+a];
              for(b=0;b<8;b++) p[b+b+(x<<4)]=p[b+b+(x<<4)+1]=15&(v_color[z+x]>>(c&128?0:4)),c<<=1;
            } else {
              if(font) c=font[14*v_char[z+x]+a]; else c=pcfont[14*v_char[z+x]+a];
              for(b=0;b<8;b++) p[b+b+(x<<4)]=p[b+b+(x<<4)+1]=(15&(v_color[z+x]>>(c&128?0:4)))+0x30,c<<=1;
            }
          }
          p+=r;
        }
      }
      break;
    case VIDEO_80COLUMNS:
      for(z=y=0;y<25;y++,z+=80) {
        for(a=0;a<14;a++) {
          for(x=0;x<80;x++) {
            if(v_font[z+x]&VF_SYSTEM) {
              c=pcfont[14*v_char[z+x]+a];
              for(b=0;b<8;b++) p[b+(x<<3)]=15&(v_color[z+x]>>(c&128?0:4)),c<<=1;
            } else {
              if(font) c=font[14*v_char[z+x]+a]; else c=pcfont[14*v_char[z+x]+a];
              for(b=0;b<8;b++) p[b+(x<<3)]=(15&(v_color[z+x]>>(c&128?0:4)))+0x30,c<<=1;
            }
          }
          p+=r;
        }
      }
      break;
    case VIDEO_SMZX:
      for(z=y=0;y<25;y++,z+=80) {
        for(a=0;a<14;a++) {
          for(x=0;x<40;x++) {
            if(v_font[z+x]&VF_SYSTEM) {
              c=pcfont[14*v_char[z+x]+a];
              for(b=0;b<8;b++) p[b+b+(x<<4)]=p[b+b+(x<<4)+1]=15&(v_color[z+x]>>(c&128?0:4)),c<<=1;
            } else if(!(a&1)) {
              if(font) c=font[14*v_char[z+x]+a]; else c=pcfont[14*v_char[z+x]+a];
              if(font) d=font[14*v_char[z+x]+a+1]; else d=pcfont[14*v_char[z+x]+a+1];
              if(!(v_font[z+x]&VF_ALTERNATE)) {
                m=v_color[z+x]; m|=((m>>4)|(m<<4))<<8; m|=m<<16;
                for(b=0;b<8;b++) p[b+b+(x<<4)]=p[b+b+1+(x<<4)]=p[b+b+1+r+(x<<4)]=p[b+b+r+(x<<4)]=(m>>(c&128?(d&128?12:8):(d&128?0:4)))|0x80,c<<=1,d<<=1;
              } else {
              }
            }
          }
          p+=r;
        }
      }
      break;
    case VIDEO_SMZX+VIDEO_80COLUMNS:
      for(z=y=0;y<25;y++,z+=80) {
        for(a=0;a<14;a++) {
          for(x=0;x<80;x++) {
            if(v_font[z+x]&VF_SYSTEM) {
              c=pcfont[14*v_char[z+x]+a];
              for(b=0;b<8;b++) p[b+(x<<3)]=15&(v_color[z+x]>>(c&128?0:4)),c<<=1;
            } else {
              if(font) c=font[14*v_char[z+x]+a]; else c=pcfont[14*v_char[z+x]+a];
              if(!(v_font[z+x]&VF_ALTERNATE)) {
                m=v_color[z+x]; m|=((m>>4)|(m<<4))<<8; m|=m<<16;
                for(b=0;b<8;b+=2) p[b+(x<<3)]=p[b+1+(x<<3)]=(m>>"\x04\x00\x08\x0C"[(c>>6)&3])|0x80,c<<=2;
              } else {
                for(b=0;b<8;b+=2) p[b+(x<<3)]=p[b+1+(x<<3)]=((c>>2)&0x30)|0x40|((v_color[z+x]>>((c>>4)&4))&0x0F),c<<=2;
              }
            }
          }
          p+=r;
        }
      }
      break;
  }
  if(v_xcur<80 && v_ycur<25) {
    a=(v_mode&VIDEO_80COLUMNS?8:16);
    p=scrn->pixels+(4+14*v_ycur)*r+4+a*v_xcur;
    for(y=0;y<14;y++) {
      for(x=0;x<a;x++) p[x]^=((x==0 || x==7 || y==0 | y==13)?16:8);
      p+=r;
    }
  }
  if(config.show_status) {
    p=scrn->pixels+(14*25+8)*r;
    for(a=0;a<14;a++) {
      for(x=0;x<81;x++) {
        c=pcfont[14*v_status[x]+a];
        for(b=0;b<8;b++) p[b+(x<<3)]=(c&128?33:32),c<<=1;
      }
      p+=r;
    }
  }
  SDL_UnlockSurface(scrn);
  SDL_Flip(scrn);
  if(nfontanim) {
    FontAnim*q;
    Uint8 u[14];
    for(a=0;a<nfontanim;a++) {
      q=fontanim[a];
      if(q->control) {
        if(((memory[MEM_FONT_ANIM]>>(q->control&15))&1)!=(q->control>>7)) continue;
      }
      if(++q->delay==q->speed) {
        q->delay=0;
        switch(q->kind) {
          case FONTANIM_SHIFT:
            for(b=q->lo;b<=q->hi;b++) {
              memcpy(u,p=font+14*b,14);
              for(c=0;c<14;c++) p[(c+q->arg2)%14]=(u[c]*0x101)>>q->arg1;
            }
            break;
          case FONTANIM_CYCLE:
            memcpy(u,font+14*q->lo,14);
            memmove(font+14*q->lo,font+14*(q->lo+1),14*(q->hi-q->lo));
            memcpy(font+14*q->hi,u,14);
            break;
          case FONTANIM_FULL:
            memcpy(font+14*q->lo,q->raster+14*(q->arg2=(q->arg2+1)%q->arg1),14);
            break;
        }
      }
    }
  }
}

