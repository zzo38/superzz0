/*
  The resulting event structure will be modified from the original SDL events,
  and some events are already handled. The return value is 1 if any event other
  than SDL_QUIT is returned. The possible events are:

  SDL_KEYDOWN:
    Keyboard input. SDLK_KP_ENTER is remapped to SDLK_RETURN, and when num lock
    is off the numbers on the number pad are remapped to the cursor keys. The
    event.key.keysym.unicode member is not Unicode; instead, it is meant to be
    a character in the current character set, where 0x01 to 0x1F and 0x7F are
    control characters, but 0x100 to 0x11F are the graphic characters with the
    codes 0x00 to 0x1F. Codes 0x8010 to 0xFFFF are meant to be wide characters
    (remapped from TRON code), but this is not currently implemented. The other
    members have the usual meaning of SDL.

  SDL_JOYBUTTONDOWN:
    Joystick button or other control is pushed. This updates joystat->state as
    well, and event.jbutton.button is the remapped logical button number (from
    0 to 31). The other members are not meaningful.

  SDL_JOYBUTTONUP:
    Joystick button or other control is no longer pushed. This is otherwise
    like SDL_JOYBUTTONDOWN. In some cases, the mapping from physical to logical
    buttons will mean some are effectively released at the same time that some
    are active (e.g. an axis or hat moves immediately from one side to another)
    in which case only SDL_JOYBUTTONDOWN event occurs but joystat->state will
    still be updated for all of the applicable changes.

  SDL_USEREVENT:
    A timer event; the data is not used. Call set_timer to set it.

  SDL_USEREVENT+1:
    Data received from an external program (the extern_in file descriptor).
    You must call unlock_front() after you have read the data; this event
    will not be triggered any more until it is called.

  SDL_QUIT:
    Program is terminated.
*/
int next_event(void) {
  int i,j;
  static Uint16 altk=0;
  static const SDLKey numpad[11]={
    SDLK_INSERT,
    SDLK_END, SDLK_DOWN, SDLK_PAGEDOWN,
    SDLK_LEFT, 0, SDLK_RIGHT,
    SDLK_HOME, SDLK_UP, SDLK_PAGEUP,
    SDLK_DELETE,
  };
  while(SDL_WaitEvent(&event)) switch(event.type) {
    case SDL_KEYDOWN:
      if(event.key.keysym.sym>=300 && event.key.keysym.sym<=314) break;
      if(event.key.keysym.sym==SDLK_KP_ENTER) event.key.keysym.sym=SDLK_RETURN;
      if(config.text_input==2 && (event.key.keysym.mod&KMOD_ALT) && event.key.keysym.sym>=256 && event.key.keysym.sym<266) {
        altk=10*altk+event.key.keysym.sym-256;
        break;
      }
      if(event.key.keysym.sym>=256 && event.key.keysym.sym<=266 && !(event.key.keysym.mod&KMOD_NUM)) {
        event.key.keysym.unicode=0;
        event.key.keysym.sym=numpad[event.key.keysym.sym-256];
        return 1;
      }
      switch(config.text_input) {
        case 0: if(event.key.keysym.unicode>127) event.key.keysym.unicode=0; break;
#ifdef SDL_VIDEO_DRIVER_X11
        case 1:
          {
            XKeyEvent ke={.type=KeyPress,.display=xdisplay,.window=xwindow,.root=xwindow,.subwindow=xwindow,.keycode=event.key.keysym.scancode};
            char buf[2];
            // Unfortunately, we do not have the full modifier state from the original XKeyEvent, so it must be reconstructed.
            // If any keys other than those listed here are used as modifier keys, it might fail to work correctly.
            if(event.key.keysym.mod&KMOD_SHIFT) ke.state|=ShiftMask;
            if(event.key.keysym.mod&KMOD_CTRL) ke.state|=ControlMask;
            if(event.key.keysym.mod&KMOD_CAPS) ke.state|=LockMask;
            if(event.key.keysym.mod&KMOD_NUM) ke.state|=num_mask;
            if(event.key.keysym.mod&KMOD_MODE) ke.state|=mode_switch_mask;
            if(xlock) xlock();
            // This should be changed in future to determine the current character set and use that.
            // (Another function will be provided to change the current character set.)
            if(XLookupString(&ke,buf,1,0,0) && !(*buf&0x80)) event.key.keysym.unicode=*buf;
            if(xunlock) xunlock();
          }
          break;
#endif
        case 2:
          if((i=event.key.keysym.sym)<128) {
            if(event.key.keysym.mod&KMOD_CTRL) {
              if(i=='6') i='^'; else if (i=='-') i='_'; else if(i=='2') i=0;
              if(i=='?' || i=='/' || i==8) i=0x7F; else i&=0x1F;
            } else if(i>32) {
              if((event.key.keysym.mod&KMOD_CAPS) && i>='a' && i<='z') i+='A'-'a';
              if(event.key.keysym.mod&KMOD_SHIFT) i="!\"#$%&\"()*+<_>?)!@#$%^&*(;:<=>?@abcdefghijklmnopqrstuvwxyz{|}^_~ABCDEFGHIJKLMNOPQRSTUVWXYZ{|}~\x7F"[i-33];
            }
            event.key.keysym.unicode=i;
          } else if(i>=256 && i<=272) {
            event.key.keysym.unicode="0123456789./*-+\r="[i-256];
          }
          break;
        default: event.key.keysym.unicode=0;
      }
      if(config.game_key_repeat) {
        if(config.game_key_repeat>1 || rscancode==event.key.keysym.scancode) repeating=1;
        rscancode=event.key.keysym.scancode;
      }
      return 1;
    case SDL_KEYUP:
      if(config.text_input==2 && altk && (event.key.keysym.sym==SDLK_LALT || event.key.keysym.sym==SDLK_RALT)) {
        event.type=SDL_KEYDOWN;
        event.key.keysym.mod=0;
        i=altk;
        if(i<0x20 || i==0x7F) i+=0x100;
        event.key.keysym.sym=(i<0x7F?i:SDLK_WORLD_0);
        altk=0;
        if(event.key.keysym.unicode=i) return 1;
      } else if(!(event.key.keysym.mod&KMOD_ALT)) {
        altk=0;
      }
      if(event.key.keysym.sym<300 || event.key.keysym.sym>314) repeating=rscancode=0;
      break;
    case SDL_USEREVENT: case SDL_USEREVENT+1: return 1;
    case SDL_QUIT: return 0;
    case SDL_VIDEOEXPOSE: redisplay(); break;
    // All joystick events will be translated to SDL_JOYBUTTONDOWN and SDL_JOYBUTTONUP.
    // The only meaningful parameter is event.jbutton.button which will be the translated button number.
    case SDL_JOYBUTTONDOWN:
      if(joystat && (i=event.jbutton.button)<joystat->nbutton) {
        i=joystat->button[i];
        if(i<32 && !(joystat->state&(1ULL<<i))) goto push;
      }
      break;
    case SDL_JOYBUTTONUP:
      if(joystat && (i=event.jbutton.button)<joystat->nbutton) {
        i=joystat->button[i];
        if(i<32 && (joystat->state&(1ULL<<i))) goto unpush;
      }
      break;
    case SDL_JOYAXISMOTION:
      if(joystat && (i=event.jaxis.axis)<joystat->naxis) {
        if(event.jaxis.value<-config.joy_sensitivity) {
          j=joystat->axis[i+i+1]; i=joystat->axis[i+i];
          goto axispush;
        } else if(event.jaxis.value>config.joy_sensitivity) {
          j=joystat->axis[i+i]; i=joystat->axis[i+i+1];
          axispush:
          if(j<32) joystat->state&=~(1ULL<<j);
          if(i<32 && (joystat->state&(1ULL<<i))) goto push;
        } else {
          j=joystat->axis[i+i+1]; i=joystat->axis[i+i];
          if(joystat->state&(i<32?1ULL<<i:0)) {
            joystat->state&=~(j<32?1ULL<<j:0);
            goto unpush;
          } else if(joystat->state&(j<32?1ULL<<j:0)) {
            i=j;
            goto unpush;
          }
        }
      }
      break;
    case SDL_JOYHATMOTION:
      if(joystat && (j=event.jhat.hat)<joystat->nhat) {
        i=event.jhat.value;
        if(i==SDL_HAT_CENTERED) {
          i=joystat->hat[4*j+0]; if(i<32 && joystat->state&(1ULL<<i)) event.type=SDL_JOYBUTTONUP,event.jbutton.button=i,joystat->state&=~(1ULL<<i);
          i=joystat->hat[4*j+1]; if(i<32 && joystat->state&(1ULL<<i)) event.type=SDL_JOYBUTTONUP,event.jbutton.button=i,joystat->state&=~(1ULL<<i);
          i=joystat->hat[4*j+2]; if(i<32 && joystat->state&(1ULL<<i)) event.type=SDL_JOYBUTTONUP,event.jbutton.button=i,joystat->state&=~(1ULL<<i);
          i=joystat->hat[4*j+3]; if(i<32 && joystat->state&(1ULL<<i)) event.type=SDL_JOYBUTTONUP,event.jbutton.button=i,joystat->state&=~(1ULL<<i);
          if(event.type==SDL_JOYBUTTONUP) return 1; else break;
        } else if(i==SDL_HAT_UP) {
          i=DIR_N;
        } else if(i==SDL_HAT_RIGHT) {
          i=DIR_E;
        } else if(i==SDL_HAT_DOWN) {
          i=DIR_S;
        } else if(i==SDL_HAT_LEFT) {
          i=DIR_W;
        } else {
          break;
        }
        if(joystat->hat[4*j+0]<32) joystat->state&=~(1ULL<<(joystat->hat[4*j+0]));
        if(joystat->hat[4*j+1]<32) joystat->state&=~(1ULL<<(joystat->hat[4*j+0]));
        if(joystat->hat[4*j+2]<32) joystat->state&=~(1ULL<<(joystat->hat[4*j+0]));
        if(joystat->hat[4*j+3]<32) joystat->state&=~(1ULL<<(joystat->hat[4*j+0]));
        i=joystat->hat[4*j+i];
        if(i<32) goto push;
      }
      break;
    push: event.type=SDL_JOYBUTTONDOWN; event.jbutton.button=i; joystat->state|=1ULL<<i; return 1;
    unpush: event.type=SDL_JOYBUTTONUP; event.jbutton.button=i; joystat->state&=~(1ULL<<i); return 1;
  }
  event.type=SDL_QUIT;
  return 0;
}

static int j_find_map(Uint8**ar,Uint8*nu,Uint16 si,Uint16 of,Uint8 ix,Sint16 ma) {
  int i;
  if(ix>=*nu) {
    *ar=realloc(*ar,(ix+1)*si);
    if(!*ar) err(1,"Allocation failed");
    for(i=*nu*si;i<(ix+1)*si;i++) (*ar)[i]=255;
    *nu=ix+1;
  }
  if((*ar)[ix*si+of]==255) {
    if(ma<0) {
      if(joystat->nmap==32) errx(1,"Too many joystick mappings");
      ma=joystat->nmap++;
    }
    return (*ar)[ix*si+of]=ma;
  } else {
    if(ma>=0 && (*ar)[ix*si+of]!=ma) errx(1,"Joystick mapping mismatch");
    return ma=(*ar)[ix*si+of];
  }
}

typedef struct {
  Uint8*text;
  Uint32 offset[32];
  Uint32 size;
} JoyNames;

static int j_match_name(Uint8*s0,const Uint8*s1,int y) {
  Uint8*e0;
  const Uint8*e1=strchrnul(s1,';');
  size_t n;
  repeat:
  if(*s0==';' || !*s0 || !*s1) return 0;
  n=(e0=strchrnul(s0,';'))-s0;
  if(e1-s1==n && !memcmp(s0,s1,n)) {
    *s0=0xFF;
    return 1;
  }
  if(!y) return 0;
  if(y==2 && *e1 && j_match_name(s0,e1+1,2)) return 1;
  if(!*e0) return 0;
  s0=e0+1;
  goto repeat;
}

Sint32 configure_joystick(char mode,const char*text) {
  Uint8 b[64];
  static JoyNames*names=0;
  const char*t=text;
  int c,i,n;
  int m=-1;
  Uint32 lv;
  Uint16 v;
  if(!joystat) {
    joystat=calloc(1,sizeof(JoyStatus));
    if(!joystat) err(1,"Allocation failed");
  }
  switch(mode) {
    case 0: // user configuration
      while(*t && *t!=':') {
        if(*t==',') ++t;
        if(c=*t++) {
          if(*t<'0' || *t>'9') goto err1;
          n=strtol(t,(char**)&t,10);
          if(n<0 || n>253) goto err1;
        } else {
          err1: errx(1,"Error in joystick configuration {%s} near position %ld/%ld",text,(long)(t-text),(long)strlen(text));
        }
        switch(c) {
          case '*': m=j_find_map(&joystat->button,&joystat->nbutton,1,0,n,m); break;
          case '-': case '+': m=j_find_map(&joystat->axis,&joystat->naxis,2,(c=='+'?1:0),n,m); break;
          case 'n': case 's': case 'e': case 'w': m=j_find_map(&joystat->hat,&joystat->nhat,4,(c=='e'?0:c=='n'?1:c=='w'?2:3),n,m); break;
          default: goto err1;
        }
      }
      if(m<0 || *t++!=':') goto err1;
      lv=0;
      while(*t!=':') switch(c=*t++) {
        case '*': lv=0xFF; break;
        case '0': lv|=1<<JL_NORMAL; break;
        case '1': lv|=1<<JL_LEVEL1; break;
        case '2': lv|=1<<JL_LEVEL2; break;
        case '3': lv|=1<<JL_LEVEL3; break;
        case '4': lv|=1<<JL_LEVEL4; break;
        case 'T': lv|=1<<JL_TEXT_WINDOW; break;
        case 'I': lv|=1<<JL_ITEM_WINDOW; break;
        case 'C': lv|=1<<JL_CUSTOM_WINDOW; break;
        default: goto err1;
      }
      t++;
      if(*t=='"') {
        if(!names) {
          names=calloc(1,sizeof(JoyNames));
          if(!names) err(1,"Allocation failed");
          names->text=strdup(";");
          if(!names->text) err(1,"Allocation failed");
          names->size=2;
        }
        v=0x8000;
        i=0;
        while((c=*++t)!='"') {
          if(!c) goto err1;
          if(i==63) errx(1,"Joystick label string is too long: %s",text);
          if(c=='\\') {
            switch(c=*++t) {
              case '\\': case '"': b[i++]=c; break;
              case 'E': b[i++]=16; break;
              case 'W': b[i++]=17; break;
              case 'n': b[i++]=24; break;
              case 's': b[i++]=25; break;
              case 'e': b[i++]=26; break;
              case 'w': b[i++]=27; break;
              case 'N': b[i++]=30; break;
              case 'S': b[i++]=31; break;
              case 'x':
                c=*++t;
                if(c>='0' && c<='9') n=c-'0'; else if(c>='A' && c<='F') n=c+10-'A'; else if(c>='a' && c<='f') n=c+10-'a'; else goto err1;
                n<<=4;
                c=*++t;
                if(c>='0' && c<='9') n+=c-'0'; else if(c>='A' && c<='F') n+=c+10-'A'; else if(c>='a' && c<='f') n+=c+10-'a'; else goto err1;
                b[i++]=n;
                break;
              default: goto err1;
            }
          } else {
            b[i++]=c;
          }
        }
        b[i++]=0;
        if(names->offset[m]) {
          if(strcmp(names->text+names->offset[m],b)) errx(1,"Joystick mapping mismatch");
        } else {
          names->text=realloc(names->text,names->size+i);
          if(!names->text) err(1,"Allocation failed");
          memcpy(names->text+names->size,b,i);
          names->offset[m]=names->size;
          names->size+=i;
        }
        if(*t=='"') t++;
        if(*t==',') t++;
      } else {
        v=0;
      }
      if(*t=='#') {
        switch(c=*++t) {
          case '0': v|=JL_NORMAL+0x200; break;
          case '1': v|=JL_LEVEL1+0x200; break;
          case '2': v|=JL_LEVEL2+0x200; break;
          case '3': v|=JL_LEVEL3+0x200; break;
          case '4': v|=JL_LEVEL4+0x200; break;
          default: goto err1;
        }
      } else if(*t=='!') {
        v|=0x80;
        if(*++t=='\'') goto apos; else goto others;
      } else if(*t=='\'') {
        apos:
        v|=c=*++t;
        if(c<0x20 || c>0x7E || *++t!='\'') goto err1;
      } else if(*t=='^') {
        v|=(c=*++t)+0x100;
        if(c<0x21 || c>0x7E) goto err1;
      } else if(*t) {
        others:
        switch(*t) {
          case 'b': v|=8; break;
          case 't': v|=9; break;
          case 'r': v|=13; break;
          case 'E': v|=16; break;
          case 'W': v|=17; break;
          case 'n': v|=24; break;
          case 's': v|=25; break;
          case 'e': v|=26; break;
          case 'w': v|=27; break;
          case 'N': v|=30; break;
          case 'S': v|=31; break;
          default: goto err1;
        }
      }
      if(*t && t[1]) goto err1;
      for(i=16;i<24;i++) if(lv&(1<<(i-16))) {
        if(joystat->map[m].a[i]&0x7FFF) errx(1,"Duplicate configuration in joystick mapping: %s",text);
        joystat->map[m].a[i]=v;
      }
      break;
    case 1: // configuration in world file
      if(!names) break;
      for(i=0;i<3;i++) for(m=0;m<32;m++) if(names->offset[m] && j_match_name(names->text+names->offset[m],text,i)) return m;
      break;
    case 2: // free name data
      if(names) free(names->text);
      free(names);
      for(m=0;m<joystat->nmap;m++) for(i=16;i<24;i++) joystat->map[m].a[i]&=0x7FFF;
      break;
  }
  return -1;
}
